func TestSetLayoutStatus_MovesStatusWithCompareAndSet(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	layout := newLayout(t, q, newHall(t, pool), "Concert")

	current := layout
	for _, to := range []string{"active", "archived", "draft"} { // activate, archive, restore
		move := eventdb.SetLayoutStatusParams{
			ID: current.ID, Version: current.Version, FromStatus: current.Status, ToStatus: to,
		}
		moved, err := q.SetLayoutStatus(t.Context(), move)
		if err != nil {
			t.Fatalf("%s → %s: %v", current.Status, to, err)
		}
		if moved.Status != to || moved.Version != current.Version+1 {
			t.Errorf("%s → %s: status %q, version %d; want %s, %d",
				current.Status, to, moved.Status, moved.Version, to, current.Version+1)
		}

		// The same request again (an admin's second click, or a second admin with the same view)
		// matches nothing: the version and the status have both moved on.
		if _, err := q.SetLayoutStatus(t.Context(), move); !errors.Is(err, pgx.ErrNoRows) {
			t.Errorf("%s → %s again: got %v, want pgx.ErrNoRows", current.Status, to, err)
		}
		current = moved
	}
}

