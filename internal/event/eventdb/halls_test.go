func TestSetHallStatus_ArchivesAndRestoresWithCompareAndSet(t *testing.T) {
	q := eventdb.New(newPool(t))
	hall := createHall(t, q, createVenue(t, q, minimalVenue("Zorlu PSM")).ID, "Studio")
	archive := eventdb.SetHallStatusParams{
		ID: hall.ID, Version: hall.Version, FromStatus: "active", ToStatus: "archived",
	}

	archived, err := q.SetHallStatus(t.Context(), archive)
	if err != nil {
		t.Fatalf("archive: %v", err)
	}
	if archived.Status != "archived" || archived.Version != hall.Version+1 {
		t.Errorf("after archive: status %q, version %d; want archived, %d",
			archived.Status, archived.Version, hall.Version+1)
	}

	// The same request again (an admin's second click, or a second admin with the same view)
	// matches nothing: the version and the status have both moved on.
	if _, err := q.SetHallStatus(t.Context(), archive); !errors.Is(err, pgx.ErrNoRows) {
		t.Errorf("archive again: got %v, want pgx.ErrNoRows", err)
	}

	restored, err := q.SetHallStatus(t.Context(), eventdb.SetHallStatusParams{
		ID: hall.ID, Version: archived.Version, FromStatus: "archived", ToStatus: "active",
	})
	if err != nil {
		t.Fatalf("restore: %v", err)
	}
	if restored.Status != "active" || restored.Version != archived.Version+1 {
		t.Errorf("after restore: status %q, version %d; want active, %d",
			restored.Status, restored.Version, archived.Version+1)
	}
}

