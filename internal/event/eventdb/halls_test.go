// lockNotAvailable is the SQLSTATE Postgres gives when a lock isn't granted within lock_timeout.
const lockNotAvailable = "55P03"

// GetVenueForShare is how creating a hall checks its venue is active: while one transaction holds
// the shared lock, another can take a shared lock too (two halls created at once), but archiving
// the venue has to wait until the first commits. Instead of waiting, the second transaction gives
// up after lock_timeout, which shows the wait without a timing-dependent test.
func TestGetVenueForShare_ArchivingWaitsUntilTheCommit(t *testing.T) {
	pool := newPool(t)
	venue := createVenue(t, eventdb.New(pool), minimalVenue("Zorlu PSM"))

	holder, err := pool.Begin(t.Context())
	if err != nil {
		t.Fatalf("begin: %v", err)
	}
	defer func() { _ = holder.Rollback(t.Context()) }() // a no-op once committed
	if _, err := eventdb.New(holder).GetVenueForShare(t.Context(), venue.ID); err != nil {
		t.Fatalf("GetVenueForShare: %v", err)
	}

	// other runs fn in its own transaction that waits at most 100 ms for a lock.
	other := func(fn func(q *eventdb.Queries) error) error {
		return postgres.WithTx(t.Context(), pool, func(tx pgx.Tx) error {
			if _, err := tx.Exec(t.Context(), `SET LOCAL lock_timeout = '100ms'`); err != nil {
				return err
			}
			return fn(eventdb.New(tx))
		})
	}
	archive := func(q *eventdb.Queries) error {
		_, err := q.SetVenueStatus(t.Context(), eventdb.SetVenueStatusParams{
			ID: venue.ID, Version: venue.Version, FromStatus: "active", ToStatus: "archived",
		})
		return err
	}

	err = other(func(q *eventdb.Queries) error {
		_, err := q.GetVenueForShare(t.Context(), venue.ID)
		return err
	})
	if err != nil {
		t.Errorf("a second shared lock: got %v, want it granted at once", err)
	}

	var pgErr *pgconn.PgError
	if err := other(archive); !errors.As(err, &pgErr) || pgErr.Code != lockNotAvailable {
		t.Errorf("archive while the shared lock is held: got %v, want SQLSTATE %s (it has to wait)",
			err, lockNotAvailable)
	}

	if err := holder.Commit(t.Context()); err != nil {
		t.Fatalf("commit: %v", err)
	}
	if err := other(archive); err != nil {
		t.Errorf("archive after the commit: %v", err)
	}
}

