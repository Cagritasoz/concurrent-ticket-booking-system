func TestUpdateVenue_ReplacesColumnsAndBumpsVersion(t *testing.T) {
	q := eventdb.New(newPool(t))
	created := createVenue(t, q, fullVenue())

	params := updateParams(created)
	params.Name = "Volkswagen Arena Istanbul"
	params.Description = nil // clearing an optional column stores NULL
	updated, err := q.UpdateVenue(t.Context(), params)
	if err != nil {
		t.Fatalf("UpdateVenue: %v", err)
	}

	if updated.Name != params.Name || updated.Description != nil {
		t.Errorf("got %+v, want the new name and no description", updated)
	}
	if *updated.Region != *created.Region {
		t.Errorf("region: got %q, want it unchanged (%q)", *updated.Region, *created.Region)
	}
	if updated.Version != created.Version+1 {
		t.Errorf("version: got %d, want %d", updated.Version, created.Version+1)
	}
	if !updated.CreatedAt.Equal(created.CreatedAt) {
		t.Errorf("created_at changed from %v to %v", created.CreatedAt, updated.CreatedAt)
	}
	// now() is the time the transaction started, and the update ran in a later transaction.
	if !updated.UpdatedAt.After(created.UpdatedAt) {
		t.Errorf("updated_at: got %v, want later than %v", updated.UpdatedAt, created.UpdatedAt)
	}
}

// UpdateVenue changes nothing unless the id, the version and the status all match. The service
// reads the venue first (locked) to tell the cases apart, so here each one is only ErrNoRows.
func TestUpdateVenue_NoMatchIsErrNoRows(t *testing.T) {
	q := eventdb.New(newPool(t))
	venue := createVenue(t, q, minimalVenue("Club"))
	archived := createVenue(t, q, minimalVenue("Arena"))
	archived, err := q.SetVenueStatus(t.Context(), eventdb.SetVenueStatusParams{
		ID: archived.ID, Version: archived.Version, FromStatus: "active", ToStatus: "archived",
	})
	if err != nil {
		t.Fatalf("SetVenueStatus: %v", err)
	}

	unknown := updateParams(venue)
	unknown.ID = uuid.New()
	stale := updateParams(venue)
	stale.Version = venue.Version + 1
	for name, params := range map[string]eventdb.UpdateVenueParams{
		"unknown id":     unknown,
		"other version":  stale,
		"archived venue": updateParams(archived),
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := q.UpdateVenue(t.Context(), params); !errors.Is(err, pgx.ErrNoRows) {
				t.Errorf("got %v, want pgx.ErrNoRows", err)
			}
		})
	}
}

func TestSetVenueStatus_ArchivesAndRestoresWithCompareAndSet(t *testing.T) {
	q := eventdb.New(newPool(t))
	venue := createVenue(t, q, minimalVenue("Club"))
	archive := eventdb.SetVenueStatusParams{
		ID: venue.ID, Version: venue.Version, FromStatus: "active", ToStatus: "archived",
	}

	archived, err := q.SetVenueStatus(t.Context(), archive)
	if err != nil {
		t.Fatalf("archive: %v", err)
	}
	if archived.Status != "archived" || archived.Version != venue.Version+1 {
		t.Errorf("after archive: status %q, version %d; want archived, %d",
			archived.Status, archived.Version, venue.Version+1)
	}

	// The same request again (an admin's second click, or a second admin with the same view)
	// matches nothing: the version and the status have both moved on.
	if _, err := q.SetVenueStatus(t.Context(), archive); !errors.Is(err, pgx.ErrNoRows) {
		t.Errorf("archive again: got %v, want pgx.ErrNoRows", err)
	}

	restored, err := q.SetVenueStatus(t.Context(), eventdb.SetVenueStatusParams{
		ID: venue.ID, Version: archived.Version, FromStatus: "archived", ToStatus: "active",
	})
	if err != nil {
		t.Fatalf("restore: %v", err)
	}
	if restored.Status != "active" || restored.Version != archived.Version+1 {
		t.Errorf("after restore: status %q, version %d; want active, %d",
			restored.Status, restored.Version, archived.Version+1)
	}
}

