func TestListLayouts_OnlyTheHallsLayoutsByNameIgnoringCase(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	hallID := newHall(t, pool)
	otherHallID := newHall(t, pool)
	// Sorting by bytes would put "Concert" before "basketball", since capital letters come first
	// there; ignoring case it comes after.
	for _, name := range []string{"theatre setup", "Concert", "basketball"} {
		newLayout(t, q, hallID, name)
	}
	newLayout(t, q, otherHallID, "Arena")

	layouts, err := q.ListLayouts(t.Context(), hallID)
	if err != nil {
		t.Fatalf("ListLayouts: %v", err)
	}
	var got []string
	for _, l := range layouts {
		got = append(got, l.Name)
	}
	want := []string{"basketball", "Concert", "theatre setup"}
	if len(got) != len(want) {
		t.Fatalf("got %q, want %q", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("got %q, want %q", got, want)
		}
	}
}

