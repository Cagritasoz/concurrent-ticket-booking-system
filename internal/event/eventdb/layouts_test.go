func TestListLayouts_TheHallsLayoutsWithTheStatusByNameIgnoringCase(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	hallID := newHall(t, pool)
	otherHallID := newHall(t, pool)
	// Sorting by bytes would put "Concert" before "basketball", since capital letters come first
	// there; ignoring case it comes after.
	for _, name := range []string{"theatre setup", "Concert", "basketball"} {
		newLayout(t, q, hallID, name)
	}
	setLayoutStatus(t, q, newLayout(t, q, hallID, "Ice show"), "active")
	setLayoutStatus(t, q, newLayout(t, q, hallID, "Old stage"), "archived")
	newLayout(t, q, otherHallID, "Arena")

	for status, want := range map[string][]string{
		"draft":    {"basketball", "Concert", "theatre setup"},
		"active":   {"Ice show"},
		"archived": {"Old stage"},
	} {
		t.Run(status, func(t *testing.T) {
			layouts, err := q.ListLayouts(t.Context(), eventdb.ListLayoutsParams{HallID: hallID, Status: status})
			if err != nil {
				t.Fatalf("ListLayouts: %v", err)
			}
			if got := layoutNames(layouts); !equalNames(got, want) {
				t.Errorf("got %q, want %q", got, want)
			}
		})
	}
}

// Two archived layouts can share a name, so id has to decide their order, the same on every call.
func TestListLayouts_EqualNamesAreOrderedByID(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	hallID := newHall(t, pool)
	first := setLayoutStatus(t, q, newLayout(t, q, hallID, "Concert"), "archived")
	second := setLayoutStatus(t, q, newLayout(t, q, hallID, "Concert"), "archived")
	want := []uuid.UUID{first.ID, second.ID}
	if first.ID.Compare(second.ID) > 0 { // Postgres compares UUIDs byte by byte, like Compare
		want = []uuid.UUID{second.ID, first.ID}
	}

	layouts, err := q.ListLayouts(t.Context(), eventdb.ListLayoutsParams{HallID: hallID, Status: "archived"})
	if err != nil {
		t.Fatalf("ListLayouts: %v", err)
	}
	if len(layouts) != 2 || layouts[0].ID != want[0] || layouts[1].ID != want[1] {
		t.Errorf("got %+v, want the two layouts in id order %v", layouts, want)
	}
}

