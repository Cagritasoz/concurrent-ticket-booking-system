func TestLayoutHasSections(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	hallID := newHall(t, pool)
	layout := newLayout(t, q, hallID, "Concert")
	other := newLayout(t, q, hallID, "Basketball")
	addSection(t, pool, other.ID, "Floor") // another layout's section doesn't count

	steps := []struct {
		name     string
		layoutID uuid.UUID
		add      bool // add a section to the layout first
		want     bool
	}{
		{"no sections", layout.ID, false, false},
		{"one section", layout.ID, true, true},
		{"unknown layout", uuid.New(), false, false},
	}
	for _, step := range steps {
		if step.add {
			addSection(t, pool, step.layoutID, "Pit")
		}
		got, err := q.LayoutHasSections(t.Context(), step.layoutID)
		if err != nil {
			t.Fatalf("%s: LayoutHasSections: %v", step.name, err)
		}
		if got != step.want {
			t.Errorf("%s: got %v, want %v", step.name, got, step.want)
		}
	}
}

func TestDeleteLayout_DeletesOnlyTheExpectedVersion(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	created := newLayout(t, q, newHall(t, pool), "Basketball")
	addSection(t, pool, created.ID, "Floor")

	steps := []struct {
		name    string
		version int32
		want    int64
	}{
		{"other version", created.Version + 1, 0},
		{"current version", created.Version, 1},
		{"already deleted", created.Version, 0},
	}
	for _, step := range steps {
		deleted, err := q.DeleteLayout(t.Context(), eventdb.DeleteLayoutParams{ID: created.ID, Version: step.version})
		if err != nil {
			t.Fatalf("%s: DeleteLayout: %v", step.name, err)
		}
		if deleted != step.want {
			t.Errorf("%s: deleted %d rows, want %d", step.name, deleted, step.want)
		}
	}
	if _, err := q.GetLayout(t.Context(), created.ID); !errors.Is(err, pgx.ErrNoRows) {
		t.Errorf("GetLayout after delete: got %v, want pgx.ErrNoRows", err)
	}
	// Its sections went with it.
	if has, err := q.LayoutHasSections(t.Context(), created.ID); err != nil || has {
		t.Errorf("sections after delete: got %v, %v; want none", has, err)
	}
}
