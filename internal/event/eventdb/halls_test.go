func TestListHalls_TheVenuesHallsWithTheStatusByNameIgnoringCase(t *testing.T) {
	q := eventdb.New(newPool(t))
	venue := createVenue(t, q, minimalVenue("Zorlu PSM"))
	other := createVenue(t, q, minimalVenue("Volkswagen Arena"))
	// Sorting by bytes would put "Turkcell Stage" before "drama stage", since capital letters
	// come first there; ignoring case it comes after.
	for _, name := range []string{"Turkcell Stage", "studio", "drama stage"} {
		createHall(t, q, venue.ID, name)
	}
	archiveHall(t, q, createHall(t, q, venue.ID, "Old Hall"))
	createHall(t, q, other.ID, "Main Floor")

	for status, want := range map[string][]string{
		"active":   {"drama stage", "studio", "Turkcell Stage"},
		"archived": {"Old Hall"},
	} {
		t.Run(status, func(t *testing.T) {
			halls, err := q.ListHalls(t.Context(), eventdb.ListHallsParams{VenueID: venue.ID, Status: status})
			if err != nil {
				t.Fatalf("ListHalls: %v", err)
			}
			if got := hallNames(halls); !equalNames(got, want) {
				t.Errorf("got %q, want %q", got, want)
			}
		})
	}
}

// Two archived halls can share a name, so id has to decide their order, the same on every call.
func TestListHalls_EqualNamesAreOrderedByID(t *testing.T) {
	q := eventdb.New(newPool(t))
	venue := createVenue(t, q, minimalVenue("Zorlu PSM"))
	first := archiveHall(t, q, createHall(t, q, venue.ID, "Studio"))
	second := archiveHall(t, q, createHall(t, q, venue.ID, "Studio"))
	want := []uuid.UUID{first.ID, second.ID}
	if first.ID.Compare(second.ID) > 0 { // Postgres compares UUIDs byte by byte, like Compare
		want = []uuid.UUID{second.ID, first.ID}
	}

	halls, err := q.ListHalls(t.Context(), eventdb.ListHallsParams{VenueID: venue.ID, Status: "archived"})
	if err != nil {
		t.Fatalf("ListHalls: %v", err)
	}
	if len(halls) != 2 || halls[0].ID != want[0] || halls[1].ID != want[1] {
		t.Errorf("got %+v, want the two halls in id order %v", halls, want)
	}
}

