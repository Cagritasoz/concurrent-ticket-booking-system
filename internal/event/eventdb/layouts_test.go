func TestDeleteLayout_ReturnsHowManyRowsWereDeleted(t *testing.T) {
	pool := newPool(t)
	q := eventdb.New(pool)
	created := newLayout(t, q, newHall(t, pool), "Basketball")

	for i, want := range []int64{1, 0} { // the second delete finds nothing
		deleted, err := q.DeleteLayout(t.Context(), created.ID)
		if err != nil {
			t.Fatalf("DeleteLayout %d: %v", i+1, err)
		}
		if deleted != want {
			t.Errorf("DeleteLayout %d: deleted %d rows, want %d", i+1, deleted, want)
		}
	}
	if _, err := q.GetLayout(t.Context(), created.ID); !errors.Is(err, pgx.ErrNoRows) {
		t.Errorf("GetLayout after delete: got %v, want pgx.ErrNoRows", err)
	}
}
